import { afterEach, describe, expect, it, vi } from 'vitest'
import { createDefaultOpenAIProfile } from './apiProfiles'
import { normalizeWorkspaceSettings } from './workspaceSettings'
import { callAgentConversationTitleApi, callAgentResponsesApi, callBatchImageSingle } from './agentApi'
import { DEFAULT_PARAMS } from '../types'

const primary = createDefaultOpenAIProfile({ id: 'primary', name: '主用', apiMode: 'responses', model: 'primary-model', apiKey: 'mock-primary', baseUrl: 'https://primary.example/v1', apiProxy: false, streamImages: false })
const backup = { ...primary, id: 'backup', name: '备用', model: 'backup-model', apiKey: 'mock-backup', baseUrl: 'https://backup.example/v1' }
const settings = normalizeWorkspaceSettings({ profiles: [primary, backup], agentTextProfileId: primary.id })
const response = (text = '完成') => new Response(JSON.stringify({ id: 'response-ok', output: [{ type: 'message', content: [{ type: 'output_text', text }] }] }), { headers: { 'Content-Type': 'application/json' } })
const rejected = (status: number) => new Response(JSON.stringify({ error: { message: 'mock refusal' } }), { status })
const request = (overrides = {}) => callAgentResponsesApi({ settings, profile: primary, params: DEFAULT_PARAMS, input: [], ...overrides })
afterEach(() => { vi.restoreAllMocks(); vi.useRealTimers() })

describe('Responses failover at request acceptance boundary', () => {
  it.each([401, 402, 403, 404, 429])('switches after explicit HTTP %i rejection using the backup body and credential', async (status) => {
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(rejected(status)).mockResolvedValueOnce(response())
    const selected = vi.fn()
    expect((await request({ onProfileSelected: selected })).text).toBe('完成')
    expect(fetchMock).toHaveBeenCalledTimes(2)
    expect(String(fetchMock.mock.calls[1][0])).toContain('backup.example')
    const options = fetchMock.mock.calls[1][1]!
    expect(JSON.parse(String(options.body)).model).toBe('backup-model')
    expect(options.headers).toMatchObject({ Authorization: 'Bearer mock-backup' })
    expect(selected.mock.calls[1][0].id).toBe('backup')
    expect(selected.mock.calls[1][1]).toContain(String(status))
  })
  it.each([400, 500, 503])('does not repeat an uncertain or non-routing HTTP %i failure', async (status) => {
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(rejected(status))
    await expect(request()).rejects.toThrow('mock refusal')
    expect(fetchMock).toHaveBeenCalledTimes(1)
  })
  it('does not repeat network errors or malformed successful responses', async () => {
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockRejectedValueOnce(new TypeError('Failed to fetch'))
    await expect(request()).rejects.toThrow('Failed to fetch')
    expect(fetchMock).toHaveBeenCalledTimes(1)
    fetchMock.mockClear().mockResolvedValueOnce(new Response('invalid-json'))
    await expect(request()).rejects.toThrow()
    expect(fetchMock).toHaveBeenCalledTimes(1)
  })
  it('skips incomplete and disabled profiles and obeys the automatic switch setting', async () => {
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockImplementation(async () => response())
    const missing = normalizeWorkspaceSettings({ ...settings, profiles: settings.profiles.map((p) => p.id === primary.id ? { ...p, apiKey: '' } : p) })
    await request({ settings: missing })
    expect(String(fetchMock.mock.calls[0][0])).toContain('backup.example')
    fetchMock.mockClear()
    const disabled = { ...settings, agentFailover: { ...settings.agentFailover!, disabledIds: [primary.id] } }
    await request({ settings: disabled })
    expect(String(fetchMock.mock.calls[0][0])).toContain('backup.example')
    fetchMock.mockClear()
    await expect(request({ settings: { ...disabled, agentFailover: { ...disabled.agentFailover, enabled: false } } })).rejects.toThrow('没有已启用')
    expect(fetchMock).not.toHaveBeenCalled()
  })
  it('stops after all rejections and never fetches after cancellation', async () => {
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockImplementation(async () => rejected(429))
    await expect(request()).rejects.toThrow('mock refusal')
    expect(fetchMock).toHaveBeenCalledTimes(2)
    fetchMock.mockClear()
    const controller = new AbortController()
    controller.abort()
    await expect(request({ signal: controller.signal })).rejects.toThrow('取消')
    expect(fetchMock).not.toHaveBeenCalled()
  })
  it('does not switch after receiving a successful stream that later fails', async () => {
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(new Response('data: {"type":"error","error":{"message":"stream failed"}}\n\n', { headers: { 'Content-Type': 'text/event-stream' } }))
    const streamed = normalizeWorkspaceSettings({ ...settings, profiles: settings.profiles.map((p) => ({ ...p, streamImages: true })) })
    await expect(request({ settings: streamed })).rejects.toThrow('stream failed')
    expect(fetchMock).toHaveBeenCalledTimes(1)
  })
  it('keeps the timeout active while consuming a stream and never retries after timeout', async () => {
    vi.useFakeTimers()
    const stream = new ReadableStream<Uint8Array>({ start(controller) { controller.enqueue(new TextEncoder().encode('data: {"type":"response.output_text.delta","delta":"开始"}\n\n')) } })
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(new Response(stream, { headers: { 'Content-Type': 'text/event-stream' } }))
    const streamed = normalizeWorkspaceSettings({ ...settings, profiles: settings.profiles.map((p) => ({ ...p, streamImages: true, timeout: 1 })) })
    const pending = request({ settings: streamed })
    const result = pending.catch((error: Error) => error)
    await vi.advanceTimersByTimeAsync(1000)
    expect(await result).toBeInstanceOf(Error)
    expect(fetchMock).toHaveBeenCalledTimes(1)
  })
  it('reports batch timeouts separately from caller cancellation without repeating', async () => {
    vi.useFakeTimers()
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockImplementation(async (_url, options) => new Promise<Response>((_resolve, reject) => {
      if (options?.signal?.aborted) reject(new DOMException('Aborted', 'AbortError'))
      else options?.signal?.addEventListener('abort', () => reject(new DOMException('Aborted', 'AbortError')), { once: true })
    }))
    const timed = normalizeWorkspaceSettings({ ...settings, profiles: settings.profiles.map((p) => ({ ...p, timeout: 1 })) })
    const pending = callBatchImageSingle({ settings: timed, profile: primary, params: DEFAULT_PARAMS, batchItemId: 'item', prompt: 'test', referenceImageDataUrls: [] })
    await vi.advanceTimersByTimeAsync(1000)
    expect((await pending).error).toContain('超时')
    expect(fetchMock).toHaveBeenCalledTimes(1)
    fetchMock.mockClear()
    const controller = new AbortController()
    const canceled = callBatchImageSingle({ settings, profile: primary, params: DEFAULT_PARAMS, batchItemId: 'item', prompt: 'test', referenceImageDataUrls: [], signal: controller.signal })
    controller.abort()
    expect((await canceled).error).toBe('请求已取消')
    expect(fetchMock).toHaveBeenCalledTimes(1)
  })
  it('uses the selected model on primary and backup without changing saved defaults', async () => {
    const multi = normalizeWorkspaceSettings({ ...settings, agentModel: 'chat-b', profiles: settings.profiles.map((p) => p.apiMode === 'responses' ? { ...p, models: [p.model, 'chat-b'] } : p) })
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(rejected(401)).mockResolvedValueOnce(response())
    await request({ settings: multi })
    expect(fetchMock.mock.calls.map((call) => JSON.parse(String(call[1]?.body)).model)).toEqual(['chat-b', 'chat-b'])
    expect(multi.profiles.find((p) => p.id === primary.id)?.model).toBe(primary.model)
    expect(multi.activeProfileId).toBe(settings.activeProfileId)
  })
  it('skips profiles that do not offer the selected model and fails locally when none do', async () => {
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockResolvedValue(response())
    await request({ settings: { ...settings, agentModel: 'backup-model' } })
    expect(String(fetchMock.mock.calls[0][0])).toContain('backup.example')
    expect(JSON.parse(String(fetchMock.mock.calls[0][1]?.body)).model).toBe('backup-model')
    fetchMock.mockClear()
    await expect(request({ settings: { ...settings, agentModel: 'unavailable-model' } })).rejects.toThrow('没有已启用')
    expect(fetchMock).not.toHaveBeenCalled()
  })
  it('sends ordinary chat without image tools and enables tools explicitly without obsolete options', async () => {
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockImplementation(async () => response())
    await request({ settings: { ...settings, agentImageTools: false, agentWebSearch: true } })
    let body = JSON.parse(String(fetchMock.mock.calls[0][1]?.body))
    expect(body.tools).toEqual([{ type: 'web_search' }])
    expect(body.instructions).toContain('conversational assistant')
    await request({ settings: { ...settings, agentImageTools: true } })
    body = JSON.parse(String(fetchMock.mock.calls[1][1]?.body))
    expect(body.tools[0]).toMatchObject({ type: 'function', name: 'generate_image' })
    expect(body.tools.some((tool: { type: string }) => tool.type === 'image_generation')).toBe(false)
    expect(body.tools[0]).not.toHaveProperty('model')
    expect(body.tools[0]).not.toHaveProperty('partial_images')
  })
  it('routes title requests independently', async () => {
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(rejected(401)).mockResolvedValueOnce(response('<title>测试标题</title>'))
    expect(await callAgentConversationTitleApi({ settings, profile: primary, prompt: '测试' })).toBe('测试标题')
    expect(fetchMock).toHaveBeenCalledTimes(2)
  })
  it('routes batch image requests and returns uncertain failures without repeating', async () => {
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(rejected(401)).mockResolvedValueOnce(new Response(JSON.stringify({ id: 'batch-ok', output: [{ type: 'image_generation_call', id: 'img', result: 'aW1hZ2U=' }] })))
    const result = await callBatchImageSingle({ settings, profile: primary, params: DEFAULT_PARAMS, batchItemId: 'item', prompt: 'test', referenceImageDataUrls: [] })
    expect(result.image?.dataUrl).toContain('aW1hZ2U=')
    expect(fetchMock).toHaveBeenCalledTimes(2)
    fetchMock.mockClear().mockResolvedValueOnce(rejected(503))
    const failed = await callBatchImageSingle({ settings, profile: primary, params: DEFAULT_PARAMS, batchItemId: 'item', prompt: 'test', referenceImageDataUrls: [] })
    expect(failed.image).toBeNull()
    expect(failed.error).toContain('mock refusal')
    expect(fetchMock).toHaveBeenCalledTimes(1)
  })
})
